//! D backend — custom core-subset native seat (seat id `d`).
//!
//! D is statically typed with mandatory declarations, so this seat is a
//! custom emitter rather than a [`crate::codegen_core`] spec (same precedent
//! as `pas`/`f90`): it tracks every binding's type (`Int`/`Str`/`Bool`),
//! emits typed declarations and function signatures, and refuses anything
//! outside the core subset with the same honest `Err`s as the core.
//! Targets DMD (verified: `dmd -run`).
//!
//! Semantics notes (all verified against the real toolchain):
//! - `/` on `long` truncates toward zero (CuNi); `%` is the C-style
//!   remainder, so `cuni_mod` normalizes to Python-floored.
//! - `writeln` prints `long`/`string` natively; booleans route through
//!   `cuni_say_bool` to print `True`/`False`.
//! - `~` concatenates strings; string `<`/`==` compare lexicographically
//!   natively; `&&`/`||`/`!` are the logic operators.

use crate::ast::*;
use std::collections::{HashMap, HashSet};

#[derive(Clone, Copy, PartialEq, Eq)]
enum Ty {
    Int,
    Str,
    Bool,
    Dec,
}

fn ty_of(ty: &Type) -> Result<Ty, String> {
    match ty {
        Type::Named(n) if n == "int" => Ok(Ty::Int),
        Type::Named(n) if n == "str" => Ok(Ty::Str),
        Type::Named(n) if n == "bool" => Ok(Ty::Bool),
        Type::Named(n) if n == "dec" => Ok(Ty::Dec),
        _ => Err("type beyond core subset; refusing".into()),
    }
}

fn d_ty(t: Ty) -> &'static str {
    match t {
        Ty::Int => "long",
        Ty::Str => "string",
        Ty::Bool => "bool",
        // `dec` is a scaled long (docs/DECIMAL.md, scale 10^4).
        Ty::Dec => "long",
    }
}

/// Quote a string literal for D (`"..."`, `\xNN` for control chars).
fn d_str(s: &str) -> String {
    let mut r = String::from('"');
    for c in s.chars() {
        match c {
            '"' => r.push_str("\\\""),
            '\\' => r.push_str("\\\\"),
            '\n' => r.push_str("\\n"),
            '\t' => r.push_str("\\t"),
            '\r' => r.push_str("\\r"),
            c if (c as u32) < 0x20 || (c as u32) == 0x7f => {
                r.push_str(&format!("\\x{:02x}", c as u32))
            }
            c => r.push(c),
        }
    }
    r.push('"');
    r
}

const HEADER: &str = r#"// Generated by the CuNi core-subset backend. Do not hand-edit.
module cuni_d_seat;
import std.stdio;
import std.format;
import std.conv;
import core.int128 : Cent, mul, div, divmod, neg;

void cuni_say_int(long x) { writeln(x); }
void cuni_say_str(string x) { writeln(x); }
void cuni_say_bool(bool x) { writeln(x ? "True" : "False"); }
long cuni_mod(long a, long b) { return ((a % b) + b) % b; }
// dec (docs/DECIMAL.md §3, §6): scaled long, scale 10^4. Mul/div run
// through Cent (128-bit, core.int128) intermediates and refuse loudly on overflow;
// division by zero throws before the division. Cent has no operators in
// DMD 2.112, so arithmetic uses core.int128's free functions (mul/div/
// divmod/neg); the envelope check reads the hi/lo halves directly (a
// 128-bit signed value fits in long iff hi is all-0 with lo <= long.max
// or all-1 with lo >= long.min).
Cent cuni_cent_of(long x) {
    return Cent(lo: cast(ulong)x, hi: x < 0 ? ulong.max : 0);
}
bool cuni_cent_fits(Cent p) {
    return (p.hi == 0 && p.lo <= cast(ulong)long.max) || (p.hi == ulong.max && p.lo >= cast(ulong)long.min);
}
long cuni_dec_mul(long a, long b) {
    Cent p = div(mul(cuni_cent_of(a), cuni_cent_of(b)), cuni_cent_of(10000));
    if (!cuni_cent_fits(p)) throw new Exception("cuni: dec multiplication overflow");
    return cast(long)p.lo;
}
long cuni_dec_div(long a, long b) {
    if (b == 0) throw new Exception("cuni: dec division by zero");
    Cent p = div(mul(cuni_cent_of(a), cuni_cent_of(10000)), cuni_cent_of(b));
    if (!cuni_cent_fits(p)) throw new Exception("cuni: dec division overflow");
    return cast(long)p.lo;
}
string cuni_dec_str(long v) {
    string s = v < 0 ? "-" : "";
    Cent a = cuni_cent_of(v);
    if (v < 0) a = neg(a);
    Cent modulus;
    Cent q = divmod(a, cuni_cent_of(10000), modulus);
    long ip = cast(long)q.lo;
    long fr = cast(long)modulus.lo;
    string fs = format("%04d", fr);
    while (fs.length > 0 && fs[$-1] == '0') fs = fs[0..$-1];
    if (fs.length == 0) fs = "0";
    return s ~ to!string(ip) ~ "." ~ fs;
}
void cuni_say_dec(long x) { writeln(cuni_dec_str(x)); }
"#;

struct Emitter {
    out: String,
    level: usize,
    fns: HashSet<String>,
    fn_ret: HashMap<String, Ty>,
    scope: HashMap<String, Ty>,
}

impl Emitter {
    fn line(&mut self, text: &str) {
        if !text.is_empty() {
            self.out.push_str(&"    ".repeat(self.level));
            self.out.push_str(text);
        }
        self.out.push('\n');
    }

    fn gen_program(&mut self, program: &Program) -> Result<(), String> {
        self.out.push_str(HEADER);
        let mut script_stmts: Vec<&Stmt> = Vec::new();
        for item in &program.items {
            match item {
                Item::Def(f) => {
                    self.check_def(f)?;
                    self.fns.insert(f.name.clone());
                }
                Item::Stmt(s) => script_stmts.push(s),
                Item::Use(u) => {
                    return Err(format!("use {}: beyond core subset; refusing", u.name))
                }
                Item::Enum(_) => return Err("enum: beyond core subset; refusing".into()),
                Item::Typ(_) => return Err("typ: beyond core subset; refusing".into()),
                Item::Iface(_) => return Err("iface: beyond core subset; refusing".into()),
                Item::Ext(_) => return Err("ext: beyond core subset; refusing".into()),
            }
        }
        self.out.push('\n');
        for item in &program.items {
            if let Item::Def(f) = item {
                self.gen_def(f)?;
                self.out.push('\n');
            }
        }
        self.line("void main() {");
        self.level += 1;
        for s in script_stmts {
            self.gen_stmt(s)?;
        }
        self.level -= 1;
        self.line("}");
        Ok(())
    }

    fn check_def(&self, f: &FnDecl) -> Result<(), String> {
        if f.fallible {
            return Err(format!(
                "def {}: fallible functions beyond core subset; refusing",
                f.name
            ));
        }
        if !f.generics.is_empty() {
            return Err(format!(
                "def {}: generics beyond core subset; refusing",
                f.name
            ));
        }
        if f.is_link {
            return Err(format!("link {}: beyond core subset; refusing", f.name));
        }
        ty_of(&f.ret_type)?;
        for p in &f.params {
            ty_of(&p.ty)?;
        }
        Ok(())
    }

    fn gen_def(&mut self, f: &FnDecl) -> Result<(), String> {
        let ret_ty = ty_of(&f.ret_type)?;
        self.fn_ret.insert(f.name.clone(), ret_ty);
        let outer = std::mem::take(&mut self.scope);
        for p in &f.params {
            self.scope.insert(p.name.clone(), ty_of(&p.ty)?);
        }
        let params: Vec<String> = f
            .params
            .iter()
            .map(|p| format!("{} {}", d_ty(ty_of(&p.ty).unwrap()), p.name))
            .collect();
        self.line(&format!(
            "{} {}({}) {{",
            d_ty(ret_ty),
            f.name,
            params.join(", ")
        ));
        self.level += 1;
        for s in &f.body {
            self.gen_stmt(s)?;
        }
        self.level -= 1;
        self.line("}");
        self.scope = outer;
        Ok(())
    }

    fn gen_stmt(&mut self, s: &Stmt) -> Result<(), String> {
        match &s.kind {
            StmtKind::Let { name, ty, value } => {
                let (v, vt) = self.gen_expr(value)?;
                if let Some(t) = ty {
                    let at = ty_of(t)?;
                    if at != vt {
                        return Err(format!(
                            "let {}: annotated type disagrees with value; refusing",
                            name
                        ));
                    }
                }
                self.scope.insert(name.clone(), vt);
                self.line(&format!("{} {} = {};", d_ty(vt), name, v));
                Ok(())
            }
            StmtKind::Mut { name, ty, value } => {
                let (v, vt) = self.gen_expr(value)?;
                if let Some(t) = ty {
                    let at = ty_of(t)?;
                    if at != vt {
                        return Err(format!(
                            "mut {}: annotated type disagrees with value; refusing",
                            name
                        ));
                    }
                }
                self.scope.insert(name.clone(), vt);
                self.line(&format!("{} {} = {};", d_ty(vt), name, v));
                Ok(())
            }
            StmtKind::Assign { target, value } => {
                if !matches!(target.kind, ExprKind::Ident(_)) {
                    return Err("complex assignment target: beyond core subset; refusing".into());
                }
                let (t, _) = self.gen_expr(target)?;
                let (v, _) = self.gen_expr(value)?;
                self.line(&format!("{} = {};", t, v));
                Ok(())
            }
            StmtKind::Ret(e) => {
                let v = match e {
                    Some(x) => self.gen_expr(x)?.0,
                    None => return Err("bare ret: beyond core subset; refusing".into()),
                };
                self.line(&format!("return {};", v));
                Ok(())
            }
            StmtKind::Fail(_) => Err("fail: beyond core subset; refusing".into()),
            StmtKind::If {
                cond,
                then_body,
                else_body,
            } => {
                let (c, ct) = self.gen_expr(cond)?;
                if ct != Ty::Bool {
                    return Err("if condition must be bool; refusing".into());
                }
                self.line(&format!("if ({}) {{", c));
                self.level += 1;
                for s in then_body {
                    self.gen_stmt(s)?;
                }
                self.level -= 1;
                if let Some(eb) = else_body {
                    self.line("} else {");
                    self.level += 1;
                    for s in eb {
                        self.gen_stmt(s)?;
                    }
                    self.level -= 1;
                }
                self.line("}");
                Ok(())
            }
            StmtKind::For { .. } => Err("for: beyond core subset; refusing".into()),
            StmtKind::Whl { cond, body } => {
                let (c, ct) = self.gen_expr(cond)?;
                if ct != Ty::Bool {
                    return Err("while condition must be bool; refusing".into());
                }
                self.line(&format!("while ({}) {{", c));
                self.level += 1;
                for s in body {
                    self.gen_stmt(s)?;
                }
                self.level -= 1;
                self.line("}");
                Ok(())
            }
            StmtKind::ExprStmt(e) => match &e.kind {
                ExprKind::Call { callee, args } => {
                    if let ExprKind::Ident(n) = &callee.kind {
                        if n == "say" {
                            if args.len() != 1 {
                                return Err(
                                    "say: exactly one argument in core subset; refusing".into()
                                );
                            }
                            let (v, vt) = self.gen_expr(args[0].expr())?;
                            let f = match vt {
                                Ty::Int => "cuni_say_int",
                                Ty::Str => "cuni_say_str",
                                Ty::Bool => "cuni_say_bool",
                                Ty::Dec => "cuni_say_dec",
                            };
                            self.line(&format!("{}({});", f, v));
                            return Ok(());
                        }
                    }
                    Err("bare call (non-say): beyond core subset; refusing".into())
                }
                _ => Err("bare expression: beyond core subset; refusing".into()),
            },
            StmtKind::Todo => Err("...: beyond core subset; refusing".into()),
        }
    }

    fn gen_expr(&mut self, e: &Expr) -> Result<(String, Ty), String> {
        match &e.kind {
            ExprKind::Int(n) => Ok((n.to_string(), Ty::Int)),
            ExprKind::Bool(b) => Ok((b.to_string(), Ty::Bool)),
            ExprKind::Str(s) => Ok((d_str(s), Ty::Str)),
            ExprKind::Float(_) => Err("float: beyond core subset; refusing".into()),
            ExprKind::Dec(v) => {
                // Scaled integer (parser scaled once, ast.rs); narrow seats
                // refuse out-of-envelope literals at emit (DECIMAL.md §7).
                if *v > i64::MAX as i128 || *v < -(i64::MAX as i128) {
                    return Err(format!(
                        "dec literal `{v}` exceeds this seat's envelope (|scaled| <= {}); refusing",
                        i64::MAX
                    ));
                }
                Ok((v.to_string(), Ty::Dec))
            }
            ExprKind::Time(_) => Err("time: beyond core subset; refusing".into()),
            ExprKind::NoneLit => Err("none: beyond core subset; refusing".into()),
            ExprKind::Ident(n) => {
                let t = self
                    .scope
                    .get(n)
                    .copied()
                    .ok_or_else(|| format!("unknown variable `{}`: refusing", n))?;
                Ok((n.clone(), t))
            }
            ExprKind::InterpStr(_) => Err("interpolated string: beyond core subset; refusing".into()),
            ExprKind::List(_) => Err("list: beyond core subset; refusing".into()),
            ExprKind::Map(_) => Err("map: beyond core subset; refusing".into()),
            ExprKind::Index { .. } => Err("indexing: beyond core subset; refusing".into()),
            ExprKind::Field { .. } => Err("field access: beyond core subset; refusing".into()),
            ExprKind::Unwrap { .. } => Err("??: beyond core subset; refusing".into()),
            ExprKind::Call { callee, args } => {
                let name = match &callee.kind {
                    ExprKind::Ident(n) => n.clone(),
                    _ => return Err("indirect call: beyond core subset; refusing".into()),
                };
                if name == "say" {
                    return Err("say: use as a statement, not an expression; refusing".into());
                }
                let ret = self.fn_ret.get(&name).copied().ok_or_else(|| {
                    format!("call to unknown function `{}`: refusing", name)
                })?;
                let mut as_: Vec<String> = Vec::new();
                for a in args {
                    if a.is_named() {
                        return Err("named arguments: beyond core subset; refusing".into());
                    }
                    as_.push(self.gen_expr(a.expr())?.0);
                }
                Ok((format!("{}({})", name, as_.join(", ")), ret))
            }
            ExprKind::Binary { op, lhs, rhs } => {
                let (l, lt) = self.gen_expr(lhs)?;
                let (r, rt) = self.gen_expr(rhs)?;
                // `dec` and `int` never mix (typeck refuses first; this is
                // defense in depth).
                if matches!(op, BinOp::Eq | BinOp::Ne | BinOp::Lt | BinOp::Gt | BinOp::Le | BinOp::Ge)
                    && ((lt == Ty::Dec) != (rt == Ty::Dec))
                {
                    return Err(
                        "mixed dec/int comparison: beyond core subset; refusing".into(),
                    );
                }
                match op {
                    BinOp::Add => {
                        if lt == Ty::Str && rt == Ty::Str {
                            return Ok((format!("({} ~ {})", l, r), Ty::Str));
                        } else if lt == Ty::Int && rt == Ty::Int {
                            return Ok((format!("({} + {})", l, r), Ty::Int));
                        } else if lt == Ty::Dec && rt == Ty::Dec {
                            return Ok((format!("({} + {})", l, r), Ty::Dec));
                        }
                        Err("mixed-type `+`: beyond core subset; refusing".into())
                    }
                    BinOp::Sub => {
                        let pair = self.require_nums(lt, rt, "-")?;
                        Ok((format!("({} - {})", l, r), pair))
                    }
                    BinOp::Mul => {
                        let pair = self.require_nums(lt, rt, "*")?;
                        if pair == Ty::Dec {
                            // trunc(a*b/10000) toward zero (DECIMAL.md §3).
                            return Ok((format!("cuni_dec_mul({}, {})", l, r), Ty::Dec));
                        }
                        Ok((format!("({} * {})", l, r), Ty::Int))
                    }
                    BinOp::Div => {
                        let pair = self.require_nums(lt, rt, "/")?;
                        if pair == Ty::Dec {
                            // trunc(a*10000/b) toward zero; b == 0 fails
                            // loudly in the helper (DECIMAL.md §3).
                            return Ok((format!("cuni_dec_div({}, {})", l, r), Ty::Dec));
                        }
                        // D `/` on long truncates toward zero (CuNi).
                        Ok((format!("({} / {})", l, r), Ty::Int))
                    }
                    BinOp::Mod => {
                        if lt == Ty::Dec || rt == Ty::Dec {
                            return Err("`%` is not defined on `dec`".into());
                        }
                        self.require_ints(lt, rt, "%")?;
                        // D `%` is C-style; CuNi wants floored.
                        Ok((format!("cuni_mod({}, {})", l, r), Ty::Int))
                    }
                    BinOp::Eq => Ok((format!("({} == {})", l, r), Ty::Bool)),
                    BinOp::Ne => Ok((format!("({} != {})", l, r), Ty::Bool)),
                    BinOp::Lt => Ok((format!("({} < {})", l, r), Ty::Bool)),
                    BinOp::Gt => Ok((format!("({} > {})", l, r), Ty::Bool)),
                    BinOp::Le => Ok((format!("({} <= {})", l, r), Ty::Bool)),
                    BinOp::Ge => Ok((format!("({} >= {})", l, r), Ty::Bool)),
                    BinOp::And => {
                        self.require_bools(lt, rt, "and")?;
                        Ok((format!("({} && {})", l, r), Ty::Bool))
                    }
                    BinOp::Or => {
                        self.require_bools(lt, rt, "or")?;
                        Ok((format!("({} || {})", l, r), Ty::Bool))
                    }
                }
            }
            ExprKind::Unary { op, expr } => {
                let (v, t) = self.gen_expr(expr)?;
                match op {
                    UnOp::Not => {
                        if t != Ty::Bool {
                            return Err("`not` on non-bool: beyond core subset; refusing".into());
                        }
                        Ok((format!("(!{})", v), Ty::Bool))
                    }
                    UnOp::Neg => {
                        if t != Ty::Int && t != Ty::Dec {
                            return Err("unary `-` on non-int/dec: beyond core subset; refusing".into());
                        }
                        Ok((format!("(-{})", v), t))
                    }
                }
            }
        }
    }

    fn require_nums(&self, l: Ty, r: Ty, op: &str) -> Result<Ty, String> {
        if l == Ty::Int && r == Ty::Int {
            Ok(Ty::Int)
        } else if l == Ty::Dec && r == Ty::Dec {
            Ok(Ty::Dec)
        } else {
            Err(format!("`{}` on mixed types: beyond core subset; refusing", op))
        }
    }

    fn require_ints(&self, l: Ty, r: Ty, op: &str) -> Result<(), String> {
        if l == Ty::Int && r == Ty::Int {
            Ok(())
        } else {
            Err(format!("`{}` on non-int: beyond core subset; refusing", op))
        }
    }

    fn require_bools(&self, l: Ty, r: Ty, op: &str) -> Result<(), String> {
        if l == Ty::Bool && r == Ty::Bool {
            Ok(())
        } else {
            Err(format!("`{}` on non-bool: beyond core subset; refusing", op))
        }
    }
}

/// Emit a D program for the CuNi core subset, or `Err` (honest refusal)
/// for anything outside it.
pub fn generate(program: &Program) -> Result<String, String> {
    let mut e = Emitter {
        out: String::new(),
        level: 0,
        fns: HashSet::new(),
        fn_ret: HashMap::new(),
        scope: HashMap::new(),
    };
    e.gen_program(program)?;
    Ok(e.out)
}
