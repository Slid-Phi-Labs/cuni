//! V backend — custom core-subset native seat (seat id `v`).
//!
//! V is statically typed with mandatory declarations, so this seat is a
//! custom emitter rather than a [`crate::codegen_core`] spec (same precedent
//! as `pas`/`f90`): it tracks every binding's type (`Int`/`Str`/`Bool`),
//! emits typed declarations and `fn` signatures, and refuses anything
//! outside the core subset with the same honest `Err`s as the core.
//! Targets V 0.4+ (verified: `v run`).
//!
//! Semantics notes (all verified against the real toolchain):
//! - `/` on `i64` truncates toward zero (CuNi); `%` is the C-style
//!   remainder, so `cuni_mod` normalizes to Python-floored.
//! - `println` prints ints/strings natively; booleans route through
//!   `cuni_say_bool` to print `True`/`False`.
//! - `+` concatenates strings; string `<`/`==` compare lexicographically
//!   natively; `&&`/`||`/`!` are the logic operators.
//! - CuNi `mut` maps exactly to V's `mut` (reassignment of an immutable
//!   binding is a compile error); CuNi `while` maps to V's `for <cond>`
//!   (V has no `while` keyword — the standard V spelling of a
//!   condition loop).

use crate::ast::*;
use std::collections::{HashMap, HashSet};

#[derive(Clone, Copy, PartialEq, Eq)]
enum Ty {
    Int,
    Str,
    Bool,
    Dec,
}

fn ty_of(ty: &Type) -> Result<Ty, String> {
    match ty {
        Type::Named(n) if n == "int" => Ok(Ty::Int),
        Type::Named(n) if n == "str" => Ok(Ty::Str),
        Type::Named(n) if n == "bool" => Ok(Ty::Bool),
        Type::Named(n) if n == "dec" => Ok(Ty::Dec),
        _ => Err("type beyond core subset; refusing".into()),
    }
}

fn v_ty(t: Ty) -> &'static str {
    match t {
        Ty::Int => "i64",
        Ty::Str => "string",
        Ty::Bool => "bool",
        // `dec` is a scaled i64 (docs/DECIMAL.md, scale 10^4).
        Ty::Dec => "i64",
    }
}

/// V 0.5.x rejects C-style typed locals (`x i64 = 10`); declarations use
/// `:=` inference, so int initializers are wrapped in `i64(...)` (a no-op
/// cast when the value is already i64) to pin the type.
fn v_init(name: &str, vt: Ty, v: &str, mutable: bool) -> String {
    let init = match vt {
        Ty::Int | Ty::Dec => format!("i64({})", v),
        _ => v.to_string(),
    };
    if mutable {
        format!("mut {} := {}", name, init)
    } else {
        format!("{} := {}", name, init)
    }
}

/// Quote a string literal for V (single-quoted; `\'` for quote).
fn v_str(s: &str) -> String {
    let mut r = String::from('\'');
    for c in s.chars() {
        match c {
            '\'' => r.push_str("\\'"),
            '\\' => r.push_str("\\\\"),
            '\n' => r.push_str("\\n"),
            '\t' => r.push_str("\\t"),
            '\r' => r.push_str("\\r"),
            // `$` starts interpolation in V strings; escape it so data
            // can never become code.
            '$' => r.push_str("\\$"),
            c if (c as u32) < 0x20 || (c as u32) == 0x7f => {
                r.push_str(&format!("\\x{:02x}", c as u32))
            }
            c => r.push(c),
        }
    }
    r.push('\'');
    r
}

const HEADER: &str = r#"// Generated by the CuNi core-subset backend. Do not hand-edit.
fn cuni_say_int(x i64) {
    println(x)
}
fn cuni_say_str(x string) {
    println(x)
}
fn cuni_say_bool(x bool) {
    println(if x { 'True' } else { 'False' })
}
fn cuni_say_dec(x i64) {
    println(cuni_dec_str(x))
}
fn cuni_mod(a i64, b i64) i64 {
    return ((a % b) + b) % b
}
// dec (docs/DECIMAL.md §3, §6): scaled i64, scale 10^4. V 0.5.2 has no
// 128-bit integer, so mul/div stay in i64 via the aq/ar split
// (a = aq*10000 + ar, |ar| < 10000) with exact overflow guards: every
// intermediate product is proven to fit, and the result magnitude is
// checked against max (max+1 on the negative side) before returning.
fn cuni_dec_mul(a i64, b i64) i64 {
    if a == 0 || b == 0 {
        return 0
    }
    aq := a / 10000
    ar := a % 10000
    // Guard aq*b: |aq| > max/|b| <=> |aq*b| > max (then |result| > max,
    // since the other terms share its sign). |b| without negating MIN
    // (lim 0 there: any nonzero aq overflows). The i64(0) first branch
    // pins the if-expression to i64: a bare 0 would infer int and
    // truncate the later branches to 32 bits.
    lim := if b == -9223372036854775807 - 1 { i64(0) } else if b < 0 { 9223372036854775807 / -b } else { 9223372036854775807 / b }
    if aq > lim || aq < -lim {
        panic('cuni: dec multiplication overflow')
    }
    bq := b / 10000
    br := b % 10000
    // |ar*bq| <= 9999 * 922337203685477 < max; |ar*br| <= 9999^2.
    t1 := aq * b
    t2 := ar * bq
    t3 := ar * br / 10000
    m1 := if t1 < 0 { -t1 } else { t1 }
    m2 := if t2 < 0 { -t2 } else { t2 }
    m3 := if t3 < 0 { -t3 } else { t3 }
    mut lim2 := 9223372036854775807 - m2 - m3
    // Negative side allows |total| <= max+1. The +1 is only formed when
    // m2+m3 >= 1 (otherwise lim2 == max and +1 would wrap to MIN);
    // with m2+m3 == 0, |total| = m1 <= max by the aq guard, so no
    // overflow is possible there.
    if (a < 0) != (b < 0) && (m2 > 0 || m3 > 0) {
        lim2 = lim2 + 1
    }
    if m1 > lim2 {
        panic('cuni: dec multiplication overflow')
    }
    return t1 + t2 + t3
}
fn cuni_dec_div(a i64, b i64) i64 {
    if b == 0 {
        panic('cuni: dec division by zero')
    }
    min_int := -9223372036854775807 - 1
    if a == min_int && b == -1 {
        panic('cuni: dec division overflow')
    }
    // trunc(a*10000/b). Split a = q*b + r: result = q*10000 +
    // trunc(r*10000/b), both terms sharing the sign of a/b.
    q := a / b
    r := a % b
    if q > 922337203685477 || q < -922337203685477 {
        panic('cuni: dec division overflow')
    }
    t1 := q * 10000
    // trunc(r*10000/b), |r| < |b|.
    mut t2 := i64(0)
    if b <= 922337203685477 && b >= -922337203685477 {
        // |r| < |b| <= max/10000, so r*10000 fits.
        t2 = r * 10000 / b
    } else {
        // |b| > max/10000: split b = d*10000 + e, r = s*d + rd.
        // r*10000/b = s + (rd*10000 - s*e)/b; the correction f lies in
        // (-1.000001, 1.000001), so term2 = s + trunc(f) + adj.
        d := b / 10000
        e := b % 10000
        s := r / d
        rd := r % d
        x := rd * 10000
        y := s * e
        ax := if x < 0 { -x } else { x }
        ay := if y < 0 { -y } else { y }
        same := (x >= 0) == (y >= 0)
        // |b|, MIN-safe (ab == 0 means |b| = 2^63). The i64(0) first
        // branch pins the if-expression to i64: a bare 0 would infer
        // int and truncate -b to 32 bits.
        ab := if b == min_int { i64(0) } else if b < 0 { -b } else { b }
        // ge: |x| + |y| >= |b| (only meaningful when !same).
        mut ge := false
        if !same {
            if ab == 0 {
                if ay != 0 {
                    ge = ax >= -(min_int + ay)
                }
            } else {
                ge = ax >= ab - ay
            }
        }
        mut fzero := false
        mut fpos := false
        mut f_int := false
        if same {
            fzero = x == y
            if !fzero {
                ws := if ax > ay { x > 0 } else { y < 0 }
                fpos = ws != (b < 0)
            }
        } else {
            // sign(x - y) = sign(x) here (x >= 0 covers x == 0).
            fpos = (x >= 0) != (b < 0)
            if ge {
                // |f| >= 1; f is exactly +-1 iff |x| + |y| == |b|.
                if ab == 0 {
                    f_int = ay != 0 && ax == -(min_int + ay)
                } else {
                    f_int = ax == ab - ay
                }
            }
        }
        g := if ge { if fpos { i64(1) } else { i64(-1) } } else { i64(0) }
        mut adj := i64(0)
        if !fzero && !f_int {
            if fpos && s < 0 {
                adj = i64(1)
            } else if !fpos && s > 0 {
                adj = i64(-1)
            }
        }
        t2 = s + g + adj
    }
    m1 := if t1 < 0 { -t1 } else { t1 }
    m2 := if t2 < 0 { -t2 } else { t2 }
    mut lim := 9223372036854775807 - m2
    // Negative side allows |total| <= max+1; the +1 is only formed when
    // m2 >= 1 (otherwise lim == max and +1 would wrap to MIN). With
    // m2 == 0, |total| = m1 <= max by the q guard, so no overflow is
    // possible there.
    if (a < 0) != (b < 0) && m2 > 0 {
        lim = lim + 1
    }
    if m1 > lim {
        panic('cuni: dec division overflow')
    }
    return t1 + t2
}
fn cuni_dec_str(v i64) string {
    s := if v < 0 { '-' } else { '' }
    // ip/fr via truncating division; abs each part (neither is MIN).
    ip := v / 10000
    fr := v % 10000
    aip := if ip < 0 { -ip } else { ip }
    afr := if fr < 0 { -fr } else { fr }
    mut fs := afr.str()
    for fs.len < 4 {
        fs = '0' + fs
    }
    for fs.len > 1 && fs.ends_with('0') {
        fs = fs[..fs.len - 1]
    }
    return '${s}${aip}.${fs}'
}
"#;

struct Emitter {
    out: String,
    level: usize,
    fns: HashSet<String>,
    fn_ret: HashMap<String, Ty>,
    scope: HashMap<String, Ty>,
}

impl Emitter {
    fn line(&mut self, text: &str) {
        if !text.is_empty() {
            self.out.push_str(&"\t".repeat(self.level));
            self.out.push_str(text);
        }
        self.out.push('\n');
    }

    fn gen_program(&mut self, program: &Program) -> Result<(), String> {
        self.out.push_str(HEADER);
        let mut script_stmts: Vec<&Stmt> = Vec::new();
        for item in &program.items {
            match item {
                Item::Def(f) => {
                    self.check_def(f)?;
                    self.fns.insert(f.name.clone());
                }
                Item::Stmt(s) => script_stmts.push(s),
                Item::Use(u) => {
                    return Err(format!("use {}: beyond core subset; refusing", u.name))
                }
                Item::Enum(_) => return Err("enum: beyond core subset; refusing".into()),
                Item::Typ(_) => return Err("typ: beyond core subset; refusing".into()),
                Item::Iface(_) => return Err("iface: beyond core subset; refusing".into()),
                Item::Ext(_) => return Err("ext: beyond core subset; refusing".into()),
            }
        }
        self.out.push('\n');
        for item in &program.items {
            if let Item::Def(f) = item {
                self.gen_def(f)?;
                self.out.push('\n');
            }
        }
        for s in script_stmts {
            self.gen_stmt(s)?;
        }
        Ok(())
    }

    fn check_def(&self, f: &FnDecl) -> Result<(), String> {
        if f.fallible {
            return Err(format!(
                "def {}: fallible functions beyond core subset; refusing",
                f.name
            ));
        }
        if !f.generics.is_empty() {
            return Err(format!(
                "def {}: generics beyond core subset; refusing",
                f.name
            ));
        }
        if f.is_link {
            return Err(format!("link {}: beyond core subset; refusing", f.name));
        }
        ty_of(&f.ret_type)?;
        for p in &f.params {
            ty_of(&p.ty)?;
        }
        Ok(())
    }

    fn gen_def(&mut self, f: &FnDecl) -> Result<(), String> {
        let ret_ty = ty_of(&f.ret_type)?;
        self.fn_ret.insert(f.name.clone(), ret_ty);
        let outer = std::mem::take(&mut self.scope);
        for p in &f.params {
            self.scope.insert(p.name.clone(), ty_of(&p.ty)?);
        }
        let params: Vec<String> = f
            .params
            .iter()
            .map(|p| format!("{} {}", p.name, v_ty(ty_of(&p.ty).unwrap())))
            .collect();
        self.line(&format!(
            "fn {}({}) {} {{",
            f.name,
            params.join(", "),
            v_ty(ret_ty)
        ));
        self.level += 1;
        for s in &f.body {
            self.gen_stmt(s)?;
        }
        self.level -= 1;
        self.line("}");
        self.scope = outer;
        Ok(())
    }

    fn gen_stmt(&mut self, s: &Stmt) -> Result<(), String> {
        match &s.kind {
            StmtKind::Let { name, ty, value } => {
                let (v, vt) = self.gen_expr(value)?;
                if let Some(t) = ty {
                    let at = ty_of(t)?;
                    if at != vt {
                        return Err(format!(
                            "let {}: annotated type disagrees with value; refusing",
                            name
                        ));
                    }
                }
                self.scope.insert(name.clone(), vt);
                self.line(&v_init(name, vt, &v, false));
                Ok(())
            }
            StmtKind::Mut { name, ty, value } => {
                let (v, vt) = self.gen_expr(value)?;
                if let Some(t) = ty {
                    let at = ty_of(t)?;
                    if at != vt {
                        return Err(format!(
                            "mut {}: annotated type disagrees with value; refusing",
                            name
                        ));
                    }
                }
                self.scope.insert(name.clone(), vt);
                self.line(&v_init(name, vt, &v, true));
                Ok(())
            }
            StmtKind::Assign { target, value } => {
                if !matches!(target.kind, ExprKind::Ident(_)) {
                    return Err("complex assignment target: beyond core subset; refusing".into());
                }
                let (t, _) = self.gen_expr(target)?;
                let (v, _) = self.gen_expr(value)?;
                self.line(&format!("{} = {}", t, v));
                Ok(())
            }
            StmtKind::Ret(e) => {
                let v = match e {
                    Some(x) => self.gen_expr(x)?.0,
                    None => return Err("bare ret: beyond core subset; refusing".into()),
                };
                self.line(&format!("return {}", v));
                Ok(())
            }
            StmtKind::Fail(_) => Err("fail: beyond core subset; refusing".into()),
            StmtKind::If {
                cond,
                then_body,
                else_body,
            } => {
                let (c, ct) = self.gen_expr(cond)?;
                if ct != Ty::Bool {
                    return Err("if condition must be bool; refusing".into());
                }
                self.line(&format!("if {} {{", c));
                self.level += 1;
                for s in then_body {
                    self.gen_stmt(s)?;
                }
                self.level -= 1;
                if let Some(eb) = else_body {
                    self.line("} else {");
                    self.level += 1;
                    for s in eb {
                        self.gen_stmt(s)?;
                    }
                    self.level -= 1;
                }
                self.line("}");
                Ok(())
            }
            StmtKind::For { .. } => Err("for: beyond core subset; refusing".into()),
            StmtKind::Whl { cond, body } => {
                let (c, ct) = self.gen_expr(cond)?;
                if ct != Ty::Bool {
                    return Err("while condition must be bool; refusing".into());
                }
                // V spells a condition loop `for <cond> { ... }`.
                self.line(&format!("for {} {{", c));
                self.level += 1;
                for s in body {
                    self.gen_stmt(s)?;
                }
                self.level -= 1;
                self.line("}");
                Ok(())
            }
            StmtKind::ExprStmt(e) => match &e.kind {
                ExprKind::Call { callee, args } => {
                    if let ExprKind::Ident(n) = &callee.kind {
                        if n == "say" {
                            if args.len() != 1 {
                                return Err(
                                    "say: exactly one argument in core subset; refusing".into()
                                );
                            }
                            let (v, vt) = self.gen_expr(args[0].expr())?;
                            let f = match vt {
                                Ty::Int => "cuni_say_int",
                                Ty::Str => "cuni_say_str",
                                Ty::Bool => "cuni_say_bool",
                                Ty::Dec => "cuni_say_dec",
                            };
                            self.line(&format!("{0}({1})", f, v));
                            return Ok(());
                        }
                    }
                    Err("bare call (non-say): beyond core subset; refusing".into())
                }
                _ => Err("bare expression: beyond core subset; refusing".into()),
            },
            StmtKind::Todo => Err("...: beyond core subset; refusing".into()),
        }
    }

    fn gen_expr(&mut self, e: &Expr) -> Result<(String, Ty), String> {
        match &e.kind {
            ExprKind::Int(n) => Ok((n.to_string(), Ty::Int)),
            ExprKind::Bool(b) => Ok((b.to_string(), Ty::Bool)),
            ExprKind::Str(s) => Ok((v_str(s), Ty::Str)),
            ExprKind::Float(_) => Err("float: beyond core subset; refusing".into()),
            ExprKind::Dec(v) => {
                // Scaled integer (parser scaled once, ast.rs); narrow seats
                // refuse out-of-envelope literals at emit (DECIMAL.md §7).
                if *v > i64::MAX as i128 || *v < -(i64::MAX as i128) {
                    return Err(format!(
                        "dec literal `{v}` exceeds this seat's envelope (|scaled| <= {}); refusing",
                        i64::MAX
                    ));
                }
                Ok((v.to_string(), Ty::Dec))
            }
            ExprKind::Time(_) => Err("time: beyond core subset; refusing".into()),
            ExprKind::NoneLit => Err("none: beyond core subset; refusing".into()),
            ExprKind::Ident(n) => {
                let t = self
                    .scope
                    .get(n)
                    .copied()
                    .ok_or_else(|| format!("unknown variable `{}`: refusing", n))?;
                Ok((n.clone(), t))
            }
            ExprKind::InterpStr(_) => Err("interpolated string: beyond core subset; refusing".into()),
            ExprKind::List(_) => Err("list: beyond core subset; refusing".into()),
            ExprKind::Map(_) => Err("map: beyond core subset; refusing".into()),
            ExprKind::Index { .. } => Err("indexing: beyond core subset; refusing".into()),
            ExprKind::Field { .. } => Err("field access: beyond core subset; refusing".into()),
            ExprKind::Unwrap { .. } => Err("??: beyond core subset; refusing".into()),
            ExprKind::Call { callee, args } => {
                let name = match &callee.kind {
                    ExprKind::Ident(n) => n.clone(),
                    _ => return Err("indirect call: beyond core subset; refusing".into()),
                };
                if name == "say" {
                    return Err("say: use as a statement, not an expression; refusing".into());
                }
                let ret = self.fn_ret.get(&name).copied().ok_or_else(|| {
                    format!("call to unknown function `{}`: refusing", name)
                })?;
                let mut as_: Vec<String> = Vec::new();
                for a in args {
                    if a.is_named() {
                        return Err("named arguments: beyond core subset; refusing".into());
                    }
                    as_.push(self.gen_expr(a.expr())?.0);
                }
                Ok((format!("{}({})", name, as_.join(", ")), ret))
            }
            ExprKind::Binary { op, lhs, rhs } => {
                let (l, lt) = self.gen_expr(lhs)?;
                let (r, rt) = self.gen_expr(rhs)?;
                // dec pairs (docs/DECIMAL.md §3): + / - plain, * / via
                // helpers (trunc toward zero), % refused, comparisons on
                // the scaled integers.
                if lt == Ty::Dec && rt == Ty::Dec {
                    return match op {
                        BinOp::Add => Ok((format!("({} + {})", l, r), Ty::Dec)),
                        BinOp::Sub => Ok((format!("({} - {})", l, r), Ty::Dec)),
                        BinOp::Mul => Ok((format!("cuni_dec_mul({}, {})", l, r), Ty::Dec)),
                        BinOp::Div => Ok((format!("cuni_dec_div({}, {})", l, r), Ty::Dec)),
                        BinOp::Mod => Err("`%` is not defined on `dec`".into()),
                        BinOp::Eq => Ok((format!("({} == {})", l, r), Ty::Bool)),
                        BinOp::Ne => Ok((format!("({} != {})", l, r), Ty::Bool)),
                        BinOp::Lt => Ok((format!("({} < {})", l, r), Ty::Bool)),
                        BinOp::Gt => Ok((format!("({} > {})", l, r), Ty::Bool)),
                        BinOp::Le => Ok((format!("({} <= {})", l, r), Ty::Bool)),
                        BinOp::Ge => Ok((format!("({} >= {})", l, r), Ty::Bool)),
                        _ => Err(format!("dec `{:?}`: beyond core subset; refusing", op)),
                    };
                }
                // `dec` and `int` never mix (typeck refuses first; this is
                // defense in depth).
                if (lt == Ty::Dec) != (rt == Ty::Dec) {
                    return Err("mixed dec/int: beyond core subset; refusing".into());
                }
                match op {
                    BinOp::Add => {
                        if lt == Ty::Str && rt == Ty::Str {
                            return Ok((format!("({} + {})", l, r), Ty::Str));
                        } else if lt == Ty::Int && rt == Ty::Int {
                            return Ok((format!("({} + {})", l, r), Ty::Int));
                        }
                        Err("mixed-type `+`: beyond core subset; refusing".into())
                    }
                    BinOp::Sub => {
                        self.require_ints(lt, rt, "-")?;
                        Ok((format!("({} - {})", l, r), Ty::Int))
                    }
                    BinOp::Mul => {
                        self.require_ints(lt, rt, "*")?;
                        Ok((format!("({} * {})", l, r), Ty::Int))
                    }
                    BinOp::Div => {
                        self.require_ints(lt, rt, "/")?;
                        // V `/` on i64 truncates toward zero (CuNi).
                        Ok((format!("({} / {})", l, r), Ty::Int))
                    }
                    BinOp::Mod => {
                        self.require_ints(lt, rt, "%")?;
                        // V `%` is C-style; CuNi wants floored.
                        Ok((format!("cuni_mod({}, {})", l, r), Ty::Int))
                    }
                    BinOp::Eq => Ok((format!("({} == {})", l, r), Ty::Bool)),
                    BinOp::Ne => Ok((format!("({} != {})", l, r), Ty::Bool)),
                    BinOp::Lt => Ok((format!("({} < {})", l, r), Ty::Bool)),
                    BinOp::Gt => Ok((format!("({} > {})", l, r), Ty::Bool)),
                    BinOp::Le => Ok((format!("({} <= {})", l, r), Ty::Bool)),
                    BinOp::Ge => Ok((format!("({} >= {})", l, r), Ty::Bool)),
                    BinOp::And => {
                        self.require_bools(lt, rt, "and")?;
                        Ok((format!("({} && {})", l, r), Ty::Bool))
                    }
                    BinOp::Or => {
                        self.require_bools(lt, rt, "or")?;
                        Ok((format!("({} || {})", l, r), Ty::Bool))
                    }
                }
            }
            ExprKind::Unary { op, expr } => {
                let (v, t) = self.gen_expr(expr)?;
                match op {
                    UnOp::Not => {
                        if t != Ty::Bool {
                            return Err("`not` on non-bool: beyond core subset; refusing".into());
                        }
                        Ok((format!("(!{})", v), Ty::Bool))
                    }
                    UnOp::Neg => {
                        if t != Ty::Int && t != Ty::Dec {
                            return Err("unary `-` on non-int/dec: beyond core subset; refusing".into());
                        }
                        Ok((format!("(-{})", v), t))
                    }
                }
            }
        }
    }

    fn require_ints(&self, l: Ty, r: Ty, op: &str) -> Result<(), String> {
        if l == Ty::Int && r == Ty::Int {
            Ok(())
        } else {
            Err(format!("`{}` on non-int: beyond core subset; refusing", op))
        }
    }

    fn require_bools(&self, l: Ty, r: Ty, op: &str) -> Result<(), String> {
        if l == Ty::Bool && r == Ty::Bool {
            Ok(())
        } else {
            Err(format!("`{}` on non-bool: beyond core subset; refusing", op))
        }
    }
}

/// Emit a V program for the CuNi core subset, or `Err` (honest refusal)
/// for anything outside it.
pub fn generate(program: &Program) -> Result<String, String> {
    let mut e = Emitter {
        out: String::new(),
        level: 0,
        fns: HashSet::new(),
        fn_ret: HashMap::new(),
        scope: HashMap::new(),
    };
    e.gen_program(program)?;
    Ok(e.out)
}
